const ARABIC_LETTER =
  /[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]/u;

const PRESENTATION_FORM = /[\uFB50-\uFDFF\uFE70-\uFEFF]/u;

function inRanges(
  ranges: ReadonlyArray<readonly [number, number]>,
  codePoint: number,
): boolean {
  let low = 0;
  let high = ranges.length - 1;
  while (low <= high) {
    const middle = (low + high) >> 1;
    const [start, end] = ranges[middle];
    if (codePoint < start) high = middle - 1;
    else if (codePoint > end) low = middle + 1;
    else return true;
  }
  return false;
}

function positionalForm(char: string): PositionalForm {
  const codePoint = char.codePointAt(0) ?? 0;
  if (inRanges(INITIAL_FORMS, codePoint)) return "initial";
  if (inRanges(MEDIAL_FORMS, codePoint)) return "medial";
  if (inRanges(FINAL_FORMS, codePoint)) return "final";
  if (inRanges(ISOLATED_FORMS, codePoint)) return "isolated";
  return "other";
}

/**
 * True when a word's stored order is visual: it starts with the letter that
 * is written last (final/isolated form) and ends with an initial/medial form.
 */
function wordLooksVisual(word: string): boolean | null {
  const chars = [...word];
  const first = positionalForm(chars[0]);
  if (first === "other") return null;
  if (chars.length === 1) return first === "isolated" || first === "final";
  const last = positionalForm(chars[chars.length - 1]);
  if (first === "final" || first === "isolated") {
    return last !== "final" && last !== "isolated";
  }
  return false;
}

function reverseRun(run: string): string {
  return [...run].reverse().join("");
}

/**
 * Fold presentation forms to standard letters and repair visual-order runs.
 * Pass one PDF text item at a time; returns logical-order Unicode.
 */
export function normalizePdfArabic(text: string): string {
  if (!PRESENTATION_FORM.test(text)) {
    return text.normalize("NFKC");
  }

  let output = "";
  let index = 0;
  while (index < text.length) {
    const char = text[index];
    if (!ARABIC_LETTER.test(char)) {
      output += char;
      index += 1;
      continue;
    }
    // A run spans Arabic letters and the whitespace between them: visual-order
    // storage mirrors the whole line, including word order.
    let end = index + 1;
    while (end < text.length) {
      const next = text[end];
      if (ARABIC_LETTER.test(next)) {
        end += 1;
        continue;
      }
      if (/\s/u.test(next)) {
        let probe = end + 1;
        while (probe < text.length && /\s/u.test(text[probe])) probe += 1;
        if (probe < text.length && ARABIC_LETTER.test(text[probe])) {
          end = probe;
          continue;
        }
      }
      break;
    }
    const run = text.slice(index, end);
    const words = run.split(/\s+/u).filter((part) => part.trim());
    const verdicts = words.map(wordLooksVisual).filter((v) => v !== null);
    const reversed =
      verdicts.length > 0 &&
      verdicts.filter(Boolean).length / verdicts.length >= 0.6;
    output += reversed ? reverseRun(run) : run;
    index = end;
  }
  return output.normalize("NFKC");
}
